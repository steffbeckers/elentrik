import { expect, test } from '@playwright/test';
import { gebruikTestgebruiker } from './hulp/inloggen';
import { leesPdf } from './hulp/pdf';
import { readFile } from 'node:fs/promises';
gebruikTestgebruiker(test, { voorvoegsel: 'plan-tekenen' });

test('tekenen, bewaren, plaatsen, heropenen en uitbreiden behoudt wereldcoördinaten', async ({ page, request }, info) => {
  test.setTimeout(120_000);
  page.setDefaultTimeout(10000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const r = await request.post('/api/projecten', { data: { naam: 'Getekende woning', stroomtype: '2x230V' } });
  expect(r.status()).toBe(201);
  const { id } = await r.json();
  const read = async () => (await (await request.get(`/api/projecten/${id}`)).json()).document.situatie.paginas[0];
  await page.goto(`/projecten/${id}`);
  await page.getByRole('button', { name: 'Kring stopcontacten' }).click();
  await page.getByTestId('tab-situatieschema').click();
  await page.getByTestId('plan-tekenen-leeg').click();
  const frame = page.frameLocator('iframe[title="Zelf plan tekenen"]');
  const canvas = frame.getByLabel('Tekenblad plattegrond');
  await expect(canvas).toBeVisible();
  for (const [x,y] of [[280,120],[600,120],[600,320],[280,320],[280,120]]) {
    await canvas.click({ position: { x: x!, y: y! } });
  }
  await canvas.press('Escape');
  await expect(frame.getByText('100%', { exact: true })).toBeVisible();
  await frame.getByRole('button', { name: 'Deur', exact: true }).click();
  await canvas.click({ position: { x: 420, y: 120 } });
  await frame.getByRole('button', { name: 'Raam', exact: true }).click();
  await canvas.click({ position: { x: 600, y: 230 } });
  await expect(frame.getByText('4 muren', { exact: true })).toBeVisible();
  await expect(frame.getByText('1 deur', { exact: true })).toBeVisible();
  await expect(frame.getByText('1 raam', { exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath('desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByTestId('plan-tekenen-bewaren')).toBeVisible();
  await page.screenshot({ path: info.outputPath('mobile.png') });
  await page.setViewportSize({ width: 1280, height: 720 });
  await frame.getByRole('button', { name: 'Tekst', exact: true }).click();
  await canvas.click({ position: { x: 450, y: 230 } });
  const text = frame.locator('input[type=text]');
  await text.fill('Keuken');
  await text.press('Control+s');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect.poll(async () => (await read())?.tekening?.formaat).toBe('openplan3d-v1');
  const first = await read();
  expect(JSON.parse(first.tekening.project).floors[0].walls).toHaveLength(4);
  expect(JSON.parse(first.tekening.project).floors[0].doors).toHaveLength(1);
  expect(JSON.parse(first.tekening.project).floors[0].windows).toHaveLength(1);
  expect(JSON.parse(first.tekening.project).floors[0].textAnnotations[0].text).toBe('Keuken');
  expect((await request.get(`/api/bestanden/${first.achtergrond.rasterBestandId}`)).headers()['content-type']).toContain('image/png');
  await page.getByTestId('te-plaatsen-A1').click();
  await page.getByTestId('plan-canvas').click({ position: { x: 300, y: 250 } });
  await expect.poll(async () => (await read())?.plaatsingen.length).toBe(1);
  const before = await read();
  await page.reload();
  await page.getByTestId('tab-situatieschema').click();
  await page.getByTestId('plan-tekenen-bewerken').click();
  const edit = page.frameLocator('iframe[title="Zelf plan tekenen"]');
  await expect(edit.getByText('4 muren', { exact: true })).toBeVisible();
  const editCanvas = edit.getByLabel('Tekenblad plattegrond');
  await editCanvas.click({ position: { x: 900, y: 180 } });
  await editCanvas.click({ position: { x: 1050, y: 380 } });
  await editCanvas.press('Escape');
  await page.getByTestId('plan-tekenen-bewaren').click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect.poll(async () => JSON.parse((await read()).tekening.project).floors[0].walls.length).toBe(5);
  const after = await read();
  for (const axis of ['x','y']) {
    const origin = `${axis}_cm`;
    const worldBefore = before.plaatsingen[0][axis] / before.tekening.kader.pxPerCm + before.tekening.kader[origin];
    const worldAfter = after.plaatsingen[0][axis] / after.tekening.kader.pxPerCm + after.tekening.kader[origin];
    expect(worldAfter).toBeCloseTo(worldBefore, 5);
  }
  await page.getByTestId('plan-tekenen-bewerken').click();
  await expect(editCanvas).toBeVisible();
  await editCanvas.click({ position: { x: 100, y: 100 } });
  await editCanvas.click({ position: { x: 200, y: 100 } });
  await page.getByRole('dialog').getByRole('button', { name: 'Annuleren', exact: true }).click();
  expect((await read()).tekening).toEqual(after.tekening);
  await page.getByTestId('exporteren').click();
  const download = page.waitForEvent('download');
  await page.getByTestId('export-start').click();
  const file = await download;
  const pdf = await leesPdf(new Uint8Array(await readFile((await file.path())!)));
  const index = pdf.paginaTeksten.findIndex(text => text.includes('Situatieschema'));
  expect(index).toBeGreaterThanOrEqual(0);
  expect(pdf.afbeeldingenPerPagina[index]).toBeGreaterThan(0);
  expect(errors).toEqual([]);
});
