import { beforeAll, expect, test, vi } from "vitest";
import { eq } from "drizzle-orm";
import type { Db } from "../server/db";
import { abonnementen, organization, user } from "../server/db/schema";
import { zetVrijstelling, verlengProef } from "../server/admin/bedrijfsrechten";
import { haalAdminOrganisatie } from "../server/admin/records";
import { startCheckout } from "../server/abonnementen/beheer";
import type { StripePoort } from "../server/abonnementen/stripe";
import { maakTestDb, maakTestOrganisatie } from "./db";
import { ADMIN_BILLING } from "./admin-fixtures";
let db: Db;
const actor = { id: "admin", naam: "Support", sessieId: "sessie" };
const nu = new Date("2026-11-03T12:00:00Z");
beforeAll(async () => { db = await maakTestDb(); });
const basis = async (id: string) => ({ mutatieId: crypto.randomUUID(), reden: "Supportafspraak", verwacht: (await haalAdminOrganisatie(db, id)).toegangVerwacht });
test("free access requires Stripe acknowledgement and removal restores subscription rules", async () => {
  const id = await maakTestOrganisatie(db);
  await db.update(organization).set({ proefEinde: new Date("2026-01-01") }).where(eq(organization.id, id));
  await db.insert(abonnementen).values({ organisatieId: id, stripeKlantId: "cus_test", stripeAbonnementId: "sub_test", status: "unpaid", openCheckoutSessie: "cs_open" });
  const before = await db.select().from(abonnementen);
  const body = { ...await basis(id), gegevens: { vrijgesteld: true, stripeBevestigd: false } };
  await expect(zetVrijstelling(db, actor, id, body)).rejects.toMatchObject({ statusCode: 400 });
  await zetVrijstelling(db, actor, id, { ...body, gegevens: { vrijgesteld: true, stripeBevestigd: true } });
  expect((await haalAdminOrganisatie(db, id, ADMIN_BILLING, nu)).toegang).toMatchObject({ schrijven: true, reden: "vrijgesteld" });
  const stripe = { zoekKlant: vi.fn(), maakCheckout: vi.fn() } as unknown as StripePoort;
  await expect(startCheckout(db, stripe, { maand: "price_m", jaar: "price_y" }, { organisatieId: id, formule: "maand", eigenaarEmail: "a@test.be", locale: "nl" }, nu)).rejects.toMatchObject({ statusCode: 409, data: { code: "BEDRIJF_VRIJGESTELD" } });
  expect(stripe.maakCheckout).not.toHaveBeenCalled();
  await zetVrijstelling(db, actor, id, { ...await basis(id), gegevens: { vrijgesteld: false, stripeBevestigd: true } });
  expect((await haalAdminOrganisatie(db, id, ADMIN_BILLING, nu)).toegang.schrijven).toBe(false);
  expect(await db.select().from(abonnementen)).toEqual(before);
});
test("trial is extended only into the future without resetting trial-used or Stripe", async () => {
  const id = await maakTestOrganisatie(db);
  await db.insert(user).values({ id: "trial-user", name: "Eigenaar", email: "trial@test.be", proefGebruikt: true });
  await db.update(organization).set({ proefEinde: new Date("2026-11-10") }).where(eq(organization.id, id));
  for (const einddatum of ["2026-11-02", "2026-11-09", "2026-02-30", "1800-01-01", "1900-01-01"]) await expect(verlengProef(db, actor, id, { ...await basis(id), gegevens: { einddatum, stripeBevestigd: false } }, nu)).rejects.toMatchObject({ statusCode: 400 });
  await verlengProef(db, actor, id, { ...await basis(id), gegevens: { einddatum: "2026-12-01", stripeBevestigd: false } }, nu);
  expect((await haalAdminOrganisatie(db, id)).toegang.proefEinde).toBe("2026-12-01T23:00:00.000Z");
  expect((await db.select().from(user).where(eq(user.id, "trial-user")))[0]!.proefGebruikt).toBe(true);
  await db.insert(abonnementen).values({ organisatieId: id, stripeKlantId: "cus_open", openCheckoutSessie: "cs_open" });
  await expect(verlengProef(db, actor, id, { ...await basis(id), gegevens: { einddatum: "2027-01-01", stripeBevestigd: false } }, nu)).rejects.toMatchObject({ statusCode: 400 });
});
